#!/usr/bin/env ruby
# frozen_string_literal: true

# Generates the SDK's resource methods from the Ampost OpenAPI document. Standard library only.
#
#     ruby scripts/generate.rb                                    # from the committed openapi.json
#     ruby scripts/generate.rb --spec https://api.ampost.io/openapi.json
#     ruby scripts/generate.rb --spec ../path/to/openapi.json
#
# With --spec, the document is first saved as openapi.json, so the snapshot and the code always match.
# Output (never edit by hand):
#     lib/ampost/generated/resources.rb   a class per tag, one method per operation, with YARD docs
#                                         from the spec, the resource readers and OPERATIONS

require "json"
require "net/http"
require "optparse"
require "uri"

ROOT = File.expand_path("..", __dir__)
SNAPSHOT = File.join(ROOT, "openapi.json")
OUT = File.join(ROOT, "lib", "ampost", "generated", "resources.rb")
HEADER = "# Generated by scripts/generate.rb from openapi.json. Do not edit by hand: run `ruby scripts/generate.rb`."
HTTP_METHODS = %w[get post put patch delete].freeze
REF_PREFIX = "#/components/schemas/"

# Method names that read better than the ones derived from the operationId (tag prefix stripped).
# A new operation needs no entry: it gets the derived name. Keep in step with ampost-python.
METHOD_NAMES = {
  "media_upload_create" => "create_upload",
  "media_upload_status" => "get_upload",
  "accounts_connect_status" => "get_connect_request",
  "queue_get" => "get_queue",
  "queue_update" => "update_queue",
  "queue_slots" => "get_queue_slots",
  "analytics_posts" => "list_posts",
  "analytics_overview" => "get_overview",
  "analytics_followers" => "list_followers",
  "webhooks_deliveries_list" => "list_deliveries",
  "docs_search" => "search",
  "feedback_submit" => "submit"
}.freeze

# Keyword arguments every method takes (see Ampost::Client#request); a query parameter must not reuse them.
OPTION_NAMES = %w[timeout max_retries extra_headers idempotency_key].freeze

RUBY_KEYWORDS = %w[
  __ENCODING__ __LINE__ __FILE__ BEGIN END alias and begin break case class def defined? do else elsif end
  ensure false for if in module next nil not or redo rescue retry return self super then true undef unless
  until when while yield
].freeze

def snake(value)
  value.gsub(/[-\s]+/, "_").gsub(/(?<=[a-z0-9])([A-Z])/, '_\1').downcase
end

def pascal(value)
  value.split(/[-_\s]+/).reject(&:empty?).map { |part| part[0].upcase + part[1..] }.join
end

# A local variable name for an API name (`platformSetId` -> `platform_set_id`).
def rb_identifier(name)
  name = snake(name)
  RUBY_KEYWORDS.include?(name) ? "#{name}_" : name
end

# JSON.stringify(value, null, 2): the formatting of the other SDKs' snapshots and scripts/export-openapi.ts.
# (JSON.pretty_generate differs on empty arrays and objects in older json gems.)
def js_json(value, indent = "")
  inner = "#{indent}  "
  case value
  when Hash
    return "{}" if value.empty?

    "{\n#{value.map { |k, v| "#{inner}#{JSON.generate(k.to_s)}: #{js_json(v, inner)}" }.join(",\n")}\n#{indent}}"
  when Array
    return "[]" if value.empty?

    "[\n#{value.map { |v| "#{inner}#{js_json(v, inner)}" }.join(",\n")}\n#{indent}]"
  else
    JSON.generate(value)
  end
end

def load_spec(source)
  return JSON.parse(File.read(SNAPSHOT, encoding: "utf-8")) if source.nil?

  text = if source.match?(%r{\Ahttps?://})
           response = Net::HTTP.get_response(URI(source))
           abort "#{source}: HTTP #{response.code}" unless response.is_a?(Net::HTTPSuccess)
           response.body.force_encoding("utf-8")
         else
           File.read(source, encoding: "utf-8")
         end
  spec = JSON.parse(text)
  File.write(SNAPSHOT, "#{js_json(spec)}\n")
  spec
end

# Reads schemas for the docs: YARD types and one-line descriptions.
class Schemas
  def initialize(spec)
    @schemas = spec.dig("components", "schemas") || {}
  end

  def deref(schema)
    schema = @schemas.fetch(schema["$ref"].delete_prefix(REF_PREFIX)) while schema.is_a?(Hash) && schema.key?("$ref")
    schema
  end

  def ref_name(schema)
    schema.is_a?(Hash) && schema["$ref"] ? schema["$ref"].delete_prefix(REF_PREFIX) : nil
  end

  # A YARD type list, for example "String, nil" or "Array<Hash>".
  def yard_type(schema)
    schema = deref(schema)
    return "Object" if schema.nil? || schema == true || schema == {}
    return yard_scalar(schema["const"]) if schema.key?("const")
    return union(schema["enum"].map { |v| yard_scalar(v) }) if schema.key?("enum")

    variants = schema["anyOf"] || schema["oneOf"]
    return union(variants.map { |v| yard_type(v) }) if variants

    kind = schema["type"]
    return union(kind.map { |k| yard_type(schema.merge("type" => k)) }) if kind.is_a?(Array)

    case kind
    when "null" then "nil"
    when "string" then "String"
    when "integer" then "Integer"
    when "number" then "Numeric"
    when "boolean" then "Boolean"
    when "array" then "Array<#{yard_type(schema["items"])}>"
    when "object" then "Hash"
    else schema.key?("properties") ? "Hash" : "Object"
    end
  end

  # "One of: `a`, `b`." for an enum, else nil.
  def enum_note(schema)
    schema = deref(schema)
    values = schema.is_a?(Hash) ? schema["enum"] : nil
    values ||= (schema["anyOf"] || []).map { |v| deref(v) }.find { |v| v.is_a?(Hash) && v["enum"] }&.fetch("enum") if schema.is_a?(Hash)
    values && "One of: #{values.compact.map { |v| "`#{v}`" }.join(", ")}."
  end

  def properties(schema)
    resolved = deref(schema)
    resolved.is_a?(Hash) ? (resolved["properties"] || {}) : {}
  end

  def required(schema)
    resolved = deref(schema)
    resolved.is_a?(Hash) ? (resolved["required"] || []) : []
  end

  private

  def yard_scalar(value)
    case value
    when nil then "nil"
    when true, false then "Boolean"
    when Integer then "Integer"
    when Numeric then "Numeric"
    else "String"
    end
  end

  def union(types)
    types = types.uniq
    (types - ["nil"] + (types.include?("nil") ? ["nil"] : [])).join(", ")
  end
end

def collect_operations(spec, schemas)
  operations = []
  spec["paths"].each do |path, item|
    HTTP_METHODS.each do |method|
      op = item[method]
      next unless op

      op_id = op.fetch("operationId")
      tag = (op["tags"] || ["default"]).first
      prefix = "#{tag.tr("-", "_")}_"
      name = METHOD_NAMES[op_id] || snake(op_id.start_with?(prefix) ? op_id.delete_prefix(prefix) : op_id)
      params = op["parameters"] || []
      path_params = params.select { |p| p["in"] == "path" }.map { |p| p["name"] }.sort_by { |n| path.index("{#{n}}") }
      query = params.select { |p| p["in"] == "query" }
      query.each do |p|
        next unless OPTION_NAMES.include?(rb_identifier(p["name"]))

        abort "#{op_id}: query parameter #{p["name"]} clashes with a request option"
      end
      body_schema = op.dig("requestBody", "content", "application/json", "schema")
      status = op["responses"].keys.find { |code| code.match?(/\A2\d\d\z/) }
      response_schema = op.dig("responses", status, "content", "application/json", "schema")
      props = schemas.properties(response_schema)
      paginated = method == "get" && query.any? { |p| p["name"] == "offset" } &&
                  schemas.deref(props["data"])&.fetch("type", nil) == "array" && props.key?("pagination")
      operations << {
        id: op_id,
        tag: tag,
        name: name,
        method: method.upcase,
        path: path,
        summary: op["summary"],
        description: op["description"],
        path_params: path_params,
        query: query,
        body_schema: body_schema,
        body_name: schemas.ref_name(body_schema),
        body_required: op.dig("requestBody", "required") == true,
        response_name: schemas.ref_name(response_schema),
        has_response: !response_schema.nil?,
        item_name: paginated ? schemas.ref_name(props["data"]["items"]) : nil,
        idempotent: params.any? { |p| p["in"] == "header" && p["name"].casecmp?("idempotency-key") },
        paginated: paginated
      }
    end
  end
  operations
end

# Comment lines, each prefixed with `indent# `.
def comment(text, indent)
  text.rstrip.split("\n", -1).map { |line| line.empty? ? "#{indent}#" : "#{indent}# #{line}" }
end

def first_line(text)
  text.to_s.strip.split("\n").first.to_s
end

# Joins notes into sentences: "Only posts on this platform. One of: `a`, `b`."
def sentences(parts)
  parts = parts.compact.map(&:strip).reject(&:empty?)
  parts.each_with_index.map { |part, i| i < parts.size - 1 && !part.match?(/[.:!?]\z/) ? "#{part}." : part }.join(" ")
end

def method_source(op, schemas)
  indent = "      "
  docs = []
  docs << op[:summary] if op[:summary]
  docs << "" << op[:description].strip if op[:description]
  docs << "" << "`#{op[:method]} #{op[:path]}`"
  if op[:idempotent]
    docs << "" << "Sends an `Idempotency-Key`: yours (`idempotency_key:`), or a generated one kept across retries."
  end
  docs << "" << "Returns one page; `each` walks every item across pages." if op[:paginated]
  docs << ""
  op[:path_params].each { |p| docs << "@param #{rb_identifier(p)} [String]" }

  if op[:body_schema]
    kind = op[:body_name] ? " (`#{op[:body_name]}`)" : ""
    docs << "@param body [Hash#{op[:body_required] ? "" : ", nil"}] The request body#{kind}, with the API's field names as keys."
    required = schemas.required(op[:body_schema])
    schemas.properties(op[:body_schema]).each do |prop, prop_schema|
      note = [required.include?(prop) ? "Required." : nil, first_line(prop_schema.is_a?(Hash) ? prop_schema["description"] : nil)]
      note << schemas.enum_note(prop_schema) if note.last.empty?
      docs << "@option body [#{schemas.yard_type(prop_schema)}] :#{prop} #{sentences(note)}".rstrip
    end
  end
  op[:query].sort_by { |q| q["required"] ? 0 : 1 }.each do |p|
    schema = p["schema"] || {}
    type = schemas.yard_type(schema)
    type += ", nil" unless p["required"] || type.include?("nil")
    text = first_line(p["description"] || schema["description"])
    text = sentences([text, schemas.enum_note(schema)]) unless text.include?("`")
    docs << "@param #{rb_identifier(p["name"])} [#{type}] #{text}".rstrip
  end
  docs << "@param idempotency_key [String, nil] Sent as `Idempotency-Key`; default: a new UUID." if op[:idempotent]
  docs << "@param options [Hash] `timeout:`, `max_retries:` and `extra_headers:` for this call."
  docs << if op[:paginated]
            "@return [Ampost::Page] Items: #{op[:item_name] ? "`#{op[:item_name]}` hashes" : "hashes"}."
          elsif !op[:has_response]
            "@return [nil]"
          else
            "@return [Hash] #{op[:response_name] ? "The `#{op[:response_name]}`." : "The response."}"
          end

  args = op[:path_params].map { |p| rb_identifier(p) }
  args << (op[:body_required] ? "body" : "body = nil") if op[:body_schema]
  op[:query].sort_by { |q| q["required"] ? 0 : 1 }.each do |p|
    args << (p["required"] ? "#{rb_identifier(p["name"])}:" : "#{rb_identifier(p["name"])}: nil")
  end
  args << "**options"

  path_expr = op[:path].gsub(/\{(\w+)\}/) { "\#{path(#{rb_identifier(Regexp.last_match(1))})}" }
  call_args = [JSON.generate(op[:method]), "\"#{path_expr}\""]
  unless op[:query].empty?
    pairs = op[:query].map { |p| "#{JSON.generate(p["name"])} => #{rb_identifier(p["name"])}" }
    call_args << "query: { #{pairs.join(", ")} }"
  end
  call_args << "body: body" if op[:body_schema]
  call_args << "idempotent: true" if op[:idempotent]
  call_args << "options: options"
  call = "@client.#{op[:paginated] ? "paginate" : "request"}(#{call_args.join(", ")})"

  lines = comment(docs.join("\n"), indent)
  lines << "#{indent}def #{op[:name]}(#{args.join(", ")})"
  lines << "#{indent}  #{call}"
  lines << "#{indent}end"
  lines.join("\n")
end

def ruby_literal(value)
  case value
  when Hash then "{ #{value.map { |k, v| "#{k}: #{ruby_literal(v)}" }.join(", ")} }"
  when String then JSON.generate(value)
  else value.inspect
  end
end

def resources_source(operations, schemas)
  tags = operations.map { |op| op[:tag] }.uniq
  out = [
    "# frozen_string_literal: true",
    "",
    HEADER,
    "",
    "module Ampost",
    "  module Resources"
  ]
  tags.each_with_index do |tag, index|
    out << "" if index.positive?
    out << "    # `#{tag}` operations: `client.#{snake(tag)}`."
    out << "    class #{pascal(tag)} < Resource"
    names = []
    operations.select { |op| op[:tag] == tag }.each_with_index do |op, op_index|
      abort "#{tag} has two methods named #{op[:name]}; add a METHOD_NAMES entry" if names.include?(op[:name])

      names << op[:name]
      out << "" if op_index.positive?
      out << method_source(op, schemas)
    end
    out << "    end"
  end
  out << ""
  out << "    # Every resource of the API, one reader per tag. Ampost::Client includes it."
  out << "    module Readers"
  tags.each do |tag|
    out << "      # @return [Ampost::Resources::#{pascal(tag)}#{tag == "media" ? ", Ampost::MediaResource" : ""}]"
    out << "      attr_reader :#{snake(tag)}"
    out << ""
  end
  out << "      private"
  out << ""
  out << "      def init_resources"
  tags.each { |tag| out << "        @#{snake(tag)} = #{pascal(tag)}.new(self)" }
  out << "      end"
  out << "    end"
  out << "  end"
  out << ""
  out << "  # Every operation, for tests and tooling."
  out << "  OPERATIONS = ["
  operations.each_with_index do |op, index|
    entry = {
      operation_id: op[:id],
      resource: snake(op[:tag]),
      method: op[:name],
      http_method: op[:method],
      path: op[:path],
      idempotent: op[:idempotent],
      paginated: op[:paginated]
    }
    out << "    #{ruby_literal(entry)}.freeze#{index == operations.size - 1 ? "" : ","}"
  end
  out << "  ].freeze"
  out << "end"
  "#{out.join("\n")}\n"
end

source = nil
OptionParser.new do |parser|
  parser.banner = "Usage: ruby scripts/generate.rb [--spec URL_OR_PATH]"
  parser.on("--spec SOURCE", "URL or path of an OpenAPI document; saved as openapi.json first") { |v| source = v }
end.parse!

spec = load_spec(source)
schemas = Schemas.new(spec)
operations = collect_operations(spec, schemas)
File.write(OUT, resources_source(operations, schemas))
puts "Generated #{operations.size} operations from #{spec["info"]["title"]} #{spec["info"]["version"]}"
